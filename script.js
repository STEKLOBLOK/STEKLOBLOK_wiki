let currentGallery = [];
let currentImageIndex = 0;

function createLightbox() {
    const lightbox = document.createElement('div');
    lightbox.className = 'lightbox';
    lightbox.id = 'lightbox';
    
    lightbox.innerHTML = `
        <span class="lightbox-close" onclick="closeLightbox()">&times;</span>
        <span class="lightbox-prev" onclick="prevImage()">❮</span>
        <span class="lightbox-next" onclick="nextImage()">❯</span>
        <div class="lightbox-content">
            <img id="lightbox-img" src="" alt="">
            <div class="lightbox-caption" id="lightbox-caption"></div>
        </div>
    `;
    
    document.body.appendChild(lightbox);
    
    lightbox.addEventListener('click', (e) => {
        if (e.target === lightbox) {
            closeLightbox();
        }
    });
    
    document.addEventListener('keydown', handleLightboxKeys);
}

function handleLightboxKeys(e) {
    const lightbox = document.getElementById('lightbox');
    if (!lightbox || !lightbox.classList.contains('active')) return;
    
    switch(e.key) {
        case 'Escape':
            closeLightbox();
            break;
        case 'ArrowLeft':
            prevImage();
            break;
        case 'ArrowRight':
            nextImage();
            break;
    }
}

function openLightbox(images, startIndex = 0) {
    currentGallery = images;
    currentImageIndex = startIndex;
    
    const lightbox = document.getElementById('lightbox');
    const img = document.getElementById('lightbox-img');
    const caption = document.getElementById('lightbox-caption');
    
    img.src = `images/${currentGallery[currentImageIndex].src}`;
    caption.textContent = currentGallery[currentImageIndex].caption;
    
    lightbox.classList.add('active');
    document.body.style.overflow = 'hidden';
    
    updateLightboxArrows();
}

function closeLightbox() {
    const lightbox = document.getElementById('lightbox');
    lightbox.classList.remove('active');
    document.body.style.overflow = '';
}

function nextImage() {
    if (currentGallery.length === 0) return;
    currentImageIndex = (currentImageIndex + 1) % currentGallery.length;
    updateLightboxImage();
}

function prevImage() {
    if (currentGallery.length === 0) return;
    currentImageIndex = (currentImageIndex - 1 + currentGallery.length) % currentGallery.length;
    updateLightboxImage();
}

function updateLightboxImage() {
    const img = document.getElementById('lightbox-img');
    const caption = document.getElementById('lightbox-caption');
    
    img.src = `images/${currentGallery[currentImageIndex].src}`;
    caption.textContent = currentGallery[currentImageIndex].caption;
    updateLightboxArrows();
}

function updateLightboxArrows() {
    const prev = document.querySelector('.lightbox-prev');
    const next = document.querySelector('.lightbox-next');
    
    if (currentGallery.length <= 1) {
        prev.style.display = 'none';
        next.style.display = 'none';
    } else {
        prev.style.display = 'flex';
        next.style.display = 'flex';
    }
}

window.closeLightbox = closeLightbox;
window.prevImage = prevImage;
window.nextImage = nextImage;

